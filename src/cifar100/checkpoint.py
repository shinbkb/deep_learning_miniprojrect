"""Portable inference checkpoints from this Python pipeline (not notebook formats)."""
import torch
from .models import build_model


def save_checkpoint(path, model, config, classes, train_indices, val_indices, stage, epoch, metrics):
    torch.save(dict(format_version=1, model_state_dict=model.state_dict(), config=config,
                    class_names=list(classes), train_indices=[int(i) for i in train_indices],
                    val_indices=[int(i) for i in val_indices], stage=stage, epoch=epoch,
                    validation=metrics), path)


def load_checkpoint(path, device):
    checkpoint = torch.load(path, map_location='cpu', weights_only=True)
    if not isinstance(checkpoint, dict) or checkpoint.get('format_version') != 1:
        raise ValueError('Use a checkpoint generated by train.py; notebook checkpoint formats differ.')
    model = build_model(checkpoint['config'], pretrained=False)
    model.load_state_dict(checkpoint['model_state_dict'])
    return model.to(device), checkpoint
